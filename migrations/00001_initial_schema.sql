CREATE INDEX idx_damage_location ON material_dispatch.damage_reports(location_id);
CREATE INDEX idx_damage_dispatch ON material_dispatch.damage_reports(dispatch_order_id);
CREATE INDEX idx_damage_status_created ON material_dispatch.damage_reports(status,created_at DESC) WHERE deleted_at IS NULL;
