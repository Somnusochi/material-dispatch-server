-- +goose Up
CREATE SCHEMA material_dispatch;

-- +goose StatementBegin
CREATE FUNCTION material_dispatch.touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 NEW.updated_at = clock_timestamp();
 RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TABLE material_dispatch.sys_users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(64) NOT NULL UNIQUE CHECK (btrim(username) <> ''),
 password_hash varchar(255) NOT NULL,
 real_name varchar(64) NOT NULL,
 phone varchar(20),
 role varchar(32) NOT NULL DEFAULT 'inspector' CHECK (role IN ('admin','dispatcher','inspector')),
 status smallint NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
 last_login_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at timestamptz
);
CREATE TRIGGER trg_sys_users_updated_at BEFORE UPDATE ON material_dispatch.sys_users FOR EACH ROW EXECUTE FUNCTION material_dispatch.touch_updated_at();

CREATE TABLE material_dispatch.locations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(128) NOT NULL CHECK (btrim(name) <> ''),
 code varchar(64) UNIQUE,
 loc_type varchar(32) NOT NULL DEFAULT 'site' CHECK (loc_type IN ('warehouse','site','yard')),
 address varchar(255),
 longitude numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
 latitude numeric(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
 coordinate_system varchar(16) NOT NULL DEFAULT 'WGS84' CHECK (coordinate_system = 'WGS84'),
 manager_id bigint REFERENCES material_dispatch.sys_users(id) ON DELETE SET NULL,
 contact_phone varchar(20),
 status smallint NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
 remark text,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at timestamptz
);
CREATE TRIGGER trg_locations_updated_at BEFORE UPDATE ON material_dispatch.locations FOR EACH ROW EXECUTE FUNCTION material_dispatch.touch_updated_at();

CREATE TABLE material_dispatch.material_specs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 spec_code varchar(64) NOT NULL UNIQUE,
 name varchar(128) NOT NULL CHECK (btrim(name) <> ''),
 category varchar(64) NOT NULL DEFAULT 'counterweight',
 unit_weight_kg numeric(10,2) NOT NULL DEFAULT 0 CHECK (unit_weight_kg >= 0 AND unit_weight_kg <> 'NaN'),
 dimensions varchar(128),
 unit varchar(16) NOT NULL DEFAULT '块',
 image_url varchar(500),
 remark text,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at timestamptz
);
CREATE TRIGGER trg_material_specs_updated_at BEFORE UPDATE ON material_dispatch.material_specs FOR EACH ROW EXECUTE FUNCTION material_dispatch.touch_updated_at();

CREATE TABLE material_dispatch.material_inventories (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 location_id bigint NOT NULL REFERENCES material_dispatch.locations(id) ON DELETE RESTRICT,
 spec_id bigint NOT NULL REFERENCES material_dispatch.material_specs(id) ON DELETE RESTRICT,
 normal_qty integer NOT NULL DEFAULT 0 CHECK (normal_qty >= 0),
 damaged_qty integer NOT NULL DEFAULT 0 CHECK (damaged_qty >= 0),
 in_transit_qty integer NOT NULL DEFAULT 0 CHECK (in_transit_qty >= 0),
 version integer NOT NULL DEFAULT 1 CHECK (version > 0),
 updated_by bigint REFERENCES material_dispatch.sys_users(id) ON DELETE SET NULL,
 CONSTRAINT uk_location_spec UNIQUE (location_id,spec_id),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TRIGGER trg_material_inventories_updated_at BEFORE UPDATE ON material_dispatch.material_inventories FOR EACH ROW EXECUTE FUNCTION material_dispatch.touch_updated_at();

CREATE TABLE material_dispatch.dispatch_orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_no varchar(64) NOT NULL UNIQUE,
 from_location_id bigint NOT NULL REFERENCES material_dispatch.locations(id) ON DELETE RESTRICT,
 to_location_id bigint NOT NULL REFERENCES material_dispatch.locations(id) ON DELETE RESTRICT,
 spec_id bigint NOT NULL REFERENCES material_dispatch.material_specs(id) ON DELETE RESTRICT,
 dispatch_qty integer NOT NULL CHECK (dispatch_qty > 0),
 actual_received_qty integer CHECK (actual_received_qty BETWEEN 0 AND dispatch_qty),
 status varchar(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','in_transit','completed','cancelled')),
 priority smallint NOT NULL DEFAULT 2 CHECK (priority BETWEEN 1 AND 3),
 driver_name varchar(64), driver_phone varchar(20), vehicle_plate varchar(32),
 creator_id bigint NOT NULL REFERENCES material_dispatch.sys_users(id),
 dispatcher_id bigint REFERENCES material_dispatch.sys_users(id),
 receiver_id bigint REFERENCES material_dispatch.sys_users(id),
 departed_at timestamptz, completed_at timestamptz,
 remark text,
 CONSTRAINT chk_different_locations CHECK (from_location_id <> to_location_id),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at timestamptz
);
CREATE TRIGGER trg_dispatch_orders_updated_at BEFORE UPDATE ON material_dispatch.dispatch_orders FOR EACH ROW EXECUTE FUNCTION material_dispatch.touch_updated_at();

CREATE TABLE material_dispatch.damage_reports (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_no varchar(64) NOT NULL UNIQUE,
 location_id bigint NOT NULL REFERENCES material_dispatch.locations(id) ON DELETE RESTRICT,
 spec_id bigint NOT NULL REFERENCES material_dispatch.material_specs(id) ON DELETE RESTRICT,
 dispatch_order_id bigint REFERENCES material_dispatch.dispatch_orders(id) ON DELETE RESTRICT,
 damaged_qty integer NOT NULL CHECK (damaged_qty > 0),
 damage_level varchar(32) NOT NULL DEFAULT 'moderate' CHECK (damage_level IN ('minor','moderate','scrapped')),
 description text NOT NULL CHECK (btrim(description) <> ''),
 image_urls jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(image_urls) = 'array' AND NOT jsonb_path_exists(image_urls, '$[*] ? (@.type() != "string")')),
 status varchar(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','repaired','scrapped','rejected')),
 reporter_id bigint NOT NULL REFERENCES material_dispatch.sys_users(id),
 reviewer_id bigint REFERENCES material_dispatch.sys_users(id),
 reviewed_at timestamptz, review_remark text,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at timestamptz
);
CREATE TRIGGER trg_damage_reports_updated_at BEFORE UPDATE ON material_dispatch.damage_reports FOR EACH ROW EXECUTE FUNCTION material_dispatch.touch_updated_at();

CREATE TABLE material_dispatch.operation_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint, username varchar(64),
 module varchar(64) NOT NULL, action varchar(64) NOT NULL,
 target_id varchar(64), summary varchar(255) NOT NULL,
 request_id varchar(64), request_method varchar(16), request_path varchar(255),
 ip_address inet, before_data jsonb, after_data jsonb,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- +goose StatementBegin
CREATE FUNCTION material_dispatch.reject_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'operation_logs is append-only' USING ERRCODE = '55000';
END;
$$;
-- +goose StatementEnd
CREATE TRIGGER trg_operation_logs_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON material_dispatch.operation_logs FOR EACH STATEMENT EXECUTE FUNCTION material_dispatch.reject_audit_mutation();

